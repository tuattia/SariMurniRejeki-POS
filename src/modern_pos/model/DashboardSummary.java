package modern_pos.model;
public class DashboardSummary {
    private int pendapatanHariIni;
    private int totalTransaksiHariIni;
    private int jumlahUtangAktif;
    private int stokMenipis;
    
    public int getPendapatanHariIni() { return pendapatanHariIni; }
    public void setPendapatanHariIni(int pendapatanHariIni) { this.pendapatanHariIni = pendapatanHariIni; }
    public int getTotalTransaksiHariIni() { return totalTransaksiHariIni; }
    public void setTotalTransaksiHariIni(int totalTransaksiHariIni) { this.totalTransaksiHariIni = totalTransaksiHariIni; }
    public int getJumlahUtangAktif() { return jumlahUtangAktif; }
    public void setJumlahUtangAktif(int jumlahUtangAktif) { this.jumlahUtangAktif = jumlahUtangAktif; }
    public int getStokMenipis() { return stokMenipis; }
    public void setStokMenipis(int stokMenipis) { this.stokMenipis = stokMenipis; }
}